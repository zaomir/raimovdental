#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const catalogPath = join(
  repo,
  'docs',
  'raimov',
  'operations',
  'expert-dental',
  'pricing',
  'PRICE_CATALOG.json'
);
const tablePath = join(dirname(catalogPath), 'PRICE_TABLE.md');
const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));

const clean = (value) =>
  String(value ?? '')
    .replace(/\r?\n/g, ' ')
    .replace(/\|/g, '\\|')
    .replace(/\s+/g, ' ')
    .trim();

const publishable = (item) =>
  item.status !== 'proposed'
  && item.priceStatus !== 'proposed'
  && item.publishGate !== 'REQUIRES_CLINIC_APPROVAL';

const sections = catalog.directions
  .filter((direction) => direction.status !== 'proposed')
  .map((direction) => {
    const rows = direction.items
      .filter(publishable)
      .map((item) => {
        const details = [
          item.includes,
          item.exclusions ? `Не входит: ${item.exclusions}` : '',
          item.duration ? `Время: ${item.duration}` : '',
          item.limits,
          item.note,
        ]
          .filter(Boolean)
          .map(clean)
          .join('. ');
        return `| ${clean(item.name)} | ${details || '—'} | ${clean(item.price)} |`;
      })
      .join('\n');
    return `## ${clean(direction.name)}

| Наименование услуги | Что входит и важные условия | Цена |
|---|---|---|
${rows}`;
  })
  .join('\n\n');

const output = `<!-- GENERATED by scripts/raimov/sync-price-table.mjs. Do not edit by hand. -->
# Expert Dental — прайс

**Единственный источник:** \`PRICE_CATALOG.json\`  
**Статус:** clinic_confirmed · обновлено ${clean(catalog.lastUpdated)}  
**Публикация:** позиции со статусом \`proposed\` автоматически исключены.

${clean(catalog.disclaimer)}

${sections}
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(tablePath, 'utf8');
  if (current !== output) {
    console.error('PRICE_TABLE.md is stale. Run: node scripts/raimov/sync-price-table.mjs');
    process.exit(1);
  }
  console.log('PRICE_TABLE.md matches PRICE_CATALOG.json.');
} else {
  writeFileSync(tablePath, output);
  console.log(`Updated ${tablePath}`);
}
