const index = [];
let globalIdx = 1;
for (const dir of catalog.directions) {
  for (const item of dir.items) {
    const id = `memo-${slugify(item.name, globalIdx)}`;
    const filename = `${id}.md`;
    const matrixRow = matrixByProcedure[item.name];
    const content = `${bodyFor(dir.id, item.name).trimEnd()}

${prescriptionBlock(dir.id, item.name)}${footer}
`;
    writeFileSync(join(outDir, filename), content, 'utf8');
    index.push({
      memo_id: id,
      file: `by-procedure/${filename}`,
      direction: dir.id,
      direction_name: dir.name,
      procedure: item.name,
      price: item.price,
      care_sku: (matrixRow?.care_basket || []).map((x) => x.code),
      next_visit: matrixRow?.next_visit || null,
    });
    globalIdx += 1;
  }
}

writeFileSync(
  join(outDir, 'INDEX.json'),
  `${JSON.stringify(
    {
      status: 'DRAFT — medical review required',
      generated: new Date().toISOString().slice(0, 10),
      count: index.length,
      phone,
      items: index,
    },
    null,
    2,
  )}\n`,
);

writeFileSync(
  join(outDir, 'INDEX.md'),
  `# Индекс памяток по процедурам

Всего: **${index.length}** (1:1 с прайсом). Печатает администратор.

| # | Направление | Процедура | memo_id |
|---:|---|---|---|
${index
  .map((row, i) => `| ${i + 1} | ${row.direction_name} | ${row.procedure} | [\`${row.memo_id}\`](${row.file.replace('by-procedure/', '')}) |`)
  .join('\n')}
`,
);

